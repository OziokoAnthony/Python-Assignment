# Exercise 12 — Use Comparison Operators
# Objective: Understand comparison operators in Python.
# 
# Question:
# Compare two numbers using comparison operators. Print the results.
# 
# Expected output:
# 10 > 5: True
# 10 < 5: False
# 10 == 10: True
# 10 != 5: True
# 10 >= 5: True
# 10 <= 5: False

a = 10
b = 5

print(f"{a} > {b}: {a > b}")
print(f"{a} < {b}: {a < b}")
print(f"{a} == 10: {a == 10}")
print(f"{a} != {b}: {a != b}")
print(f"{a} >= {b}: {a >= b}")
print(f"{a} <= {b}: {a <= b}")
