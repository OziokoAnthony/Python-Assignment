# Exercise 15 — Use Bitwise Operators
# Objective: Learn how to manipulate binary numbers using bitwise operators.
# 
# Question:
# Perform bitwise operations on the integers 5 and 3.
# 
# Expected output:
# 5 & 3 = 1
# 5 | 3 = 7
# 5 ^ 3 = 6
# 5 << 1 = 10
# 5 >> 1 = 2

a = 5
b = 3

print(f"{a} & {b} = {a & b}")
print(f"{a} | {b} = {a | b}")
print(f"{a} ^ {b} = {a ^ b}")
print(f"{a} << 1 = {a << 1}")
print(f"{a} >> 1 = {a >> 1}")
