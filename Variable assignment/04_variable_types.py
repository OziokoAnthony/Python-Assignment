# Exercise 4 — Check the Type of a Variable
# Objective: Learn how to check variable types using type().
# 
# Question:
# Declare different types of variables: an integer (age), a float (course rating), and a string (course name). Use type() to check their data types.
# 
# Expected output:
# 21 is of type <class 'int'>
# 4.9 is of type <class 'float'>
# Python Programming is of type <class 'str'>

age = 21
rating = 4.9
course = "Python Programming"

print(age, "is of type", type(age))
print(rating, "is of type", type(rating))
print(course, "is of type", type(course))
