# Exercise 8 — Convert a Boolean to an Integer
# Objective: Learn how Boolean values convert to integers.
# 
# Question:
# Convert the Boolean values True and False into integers. Print their numerical values.
# 
# Expected output:
# True as an integer: 1
# False as an integer: 0

print(f"True as an integer: {int(True)}")
print(f"False as an integer: {int(False)}")
