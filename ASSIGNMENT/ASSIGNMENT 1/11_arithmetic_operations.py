# Question:
# Perform addition, subtraction, multiplication, division, and modulus operations. Print the results.
# 
# Expected output:
# Addition: 15
# Subtraction: 5
# Multiplication: 50
# Division: 2.5
# Modulus: 0

first = 10
second = 5

print(f"Addition: {first + second}")
print(f"Subtraction: {first - second}")
print(f"Multiplication: {first * second}")
print(f"Division: {first / second}")
print(f"Modulus: {first % second}")
