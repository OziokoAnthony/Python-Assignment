# Exercise 14 — Use Assignment Operators
# Objective: Learn how assignment operators modify variables.
# 
# Question:
# Use different assignment operators to modify a variable and print the value after each operation.
# 
# Expected output:
# Initial Value: 10
# After += : 15
# After -= : 12
# After *= : 24
# After /= : 8.0
# After %= : 0.0

value = 10
print(f"Initial Value: {value}")

value += 5
print(f"After += : {value}")

value -= 3
print(f"After -= : {value}")

value *= 2
print(f"After *= : {value}")

value /= 3
print(f"After /= : {value}")

value %= 8
print(f"After %= : {value}")
